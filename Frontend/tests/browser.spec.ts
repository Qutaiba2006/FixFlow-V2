test('connection outages preserve sessions and recover using real network retry', async ({ page, request }) => {
  const user = await owner(request)
  await signIn(page, user.email, user.password)
  await page.context().setOffline(true)
  await page.getByRole('textbox', { name: 'Search reports', exact: true }).fill('unmatched')
  await navigate(page, 'My reports')
  await expect(page.getByRole('alert')).toContainText('Cannot reach the API')
  await expect(page.locator('.stat-number')).toHaveText(['—', '—', '—', '—'])
  expect(await page.evaluate(() => !!sessionStorage.getItem('fixflow-session'))).toBe(true)
  await page.context().setOffline(false)
  await page.getByRole('button', { name: 'Try again', exact: true }).click()
  await expect(page.locator('.empty')).toBeVisible()
  // Delay the real health request only; no response is mocked or substituted.
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/health', async route => { await gate; await route.continue() })
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('status')).toContainText('Gathering the latest')
  release()
  await expect(page.locator('.empty')).toBeVisible()
  // A failed auth/me request must show recovery while retaining the token.
  await page.route('**/api/auth/me', route => route.abort('internetdisconnected'))
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Let’s reconnect your workspace.' })).toBeVisible()
  await page.unroute('**/api/auth/me')
  await page.getByRole('button', { name: 'Retry connection', exact: true }).click()
  await expect(page.locator('.empty')).toBeVisible()
})

